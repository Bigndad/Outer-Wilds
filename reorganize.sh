#!/usr/bin/env bash
# Reorganise ~/.config/quickshell/outerwilds into folders.
# Usage:  bash reorganize.sh            (real run)
#         bash reorganize.sh --dry-run  (only prints what it would move)
# Safe to re-run: files already moved are skipped, edits are idempotent.
set -euo pipefail

CFG="${OW_DIR:-$HOME/.config/quickshell/outerwilds}"
ARCHIVE="${OW_ARCHIVE:-$HOME/outerwilds-archive}"
DRY=0; [ "${1:-}" = "--dry-run" ] && DRY=1

cd "$CFG"

run() { if [ $DRY = 1 ]; then echo "  [dry] $*"; else "$@"; fi; }

# --- 0. full backup first (skipped on dry run) -------------------------------
if [ $DRY = 0 ] && [ ! -e "$HOME/outerwilds-pre-reorg.tar.gz" ]; then
    tar czf "$HOME/outerwilds-pre-reorg.tar.gz" -C "$(dirname "$CFG")" "$(basename "$CFG")"
    echo "backup: ~/outerwilds-pre-reorg.tar.gz"
fi

# --- 1. file -> folder map ----------------------------------------------------
declare -A MAP=(
  [CameraRig.qml]=core
  [PlanetShader.qml]=planets
  [SatelliteHUD.qml]=hud   [hud_assets]=hud
  [WidgetLayer.qml]=widgets [WidgetSlot.qml]=widgets [WidgetCard.qml]=widgets
  [BlankWidget.qml]=widgets [ClockWidget.qml]=widgets [DateWorldWidget.qml]=widgets
  [LoopWidget.qml]=widgets  [NotesWidget.qml]=widgets [UptimeWidget.qml]=widgets
  [WorkspacesWidget.qml]=widgets [RumorWidget.qml]=widgets
  [SignalscopeWidget.qml]=widgets [NoctaliaPlugin.qml]=widgets
  [MapHost.qml]=map [MapNode.qml]=map [MapReturnChip.qml]=map [MapButton.qml]=map [MapView.qml]=map
  [RumorMap.qml]=rumor [RumorMapView.qml]=rumor
  [Signalscope.qml]=signalscope
  [HudData.qml]=data [WidgetData.qml]=data [RumorData.qml]=data
  [SignalscopeData.qml]=data [MapData.qml]=data [SignalscopeMpris.qml]=data
  [main.qml]=dev [test_mint.qml]=dev
  [Quickshell_qmldir]=dev [Quickshell_Singleton.qml]=dev
)
for f in "${!MAP[@]}"; do
  d="${MAP[$f]}"
  if [ -e "$f" ]; then
    run mkdir -p "$d"
    echo "move  $f -> $d/"
    run mv "$f" "$d/"
  fi
done

# shaders: every .frag and .qsb
run mkdir -p shaders
for f in *.frag *.qsb; do
  [ -e "$f" ] || continue
  echo "move  $f -> shaders/"
  run mv "$f" shaders/
done

# old backups leave the config dir entirely (nothing is deleted)
for b in backup "backup 2"; do
  if [ -e "$b" ]; then
    echo "move  '$b' -> $ARCHIVE/"
    run mkdir -p "$ARCHIVE"
    run mv "$b" "$ARCHIVE/"
  fi
done
[ -e qmldir ] && { run mkdir -p "$ARCHIVE"; echo "keep  old qmldir -> $ARCHIVE/qmldir.old"; run cp qmldir "$ARCHIVE/qmldir.old"; }

if [ $DRY = 1 ]; then echo "dry run finished, nothing changed"; exit 0; fi

# --- 2. fix imports + shader paths, generate the root qmldir -----------------
python3 - "$CFG" <<'PY'
import re, sys, pathlib
root = pathlib.Path(sys.argv[1])
subdirs = ["core","planets","hud","widgets","map","rumor","signalscope","data","dev"]
shader_re = re.compile(r'"([A-Za-z0-9_]+\.frag\.qsb)"')
root_obj  = re.compile(r'^[A-Za-z_][A-Za-z0-9_.]*\s*\{')

entries = []   # (kind, name, relpath)
for d in subdirs:
    for f in sorted((root/d).glob("*.qml")):
        lines = f.read_text().split("\n")
        last, idx_root = -1, None
        for i, l in enumerate(lines):
            if l.startswith("import "): last = i
            if root_obj.match(l): idx_root = i; break
        head = lines[: idx_root if idx_root is not None else len(lines)]
        if not any(l.strip() == 'import ".."' for l in head):
            at = last + 1 if last >= 0 else (idx_root or 0)
            lines.insert(at, 'import ".."')
        text = shader_re.sub(r'"../shaders/\1"', "\n".join(lines))
        f.write_text(text)
        if d != "dev":
            single = any(re.match(r'\s*pragma\s+Singleton', l) for l in head)
            entries.append(("singleton " if single else "", f.stem, f"{d}/{f.name}"))

out = ["# generated by reorganize.sh - one registry for every type in the config",
       "# add a new file here by hand: [singleton ]Name 1.0 folder/File.qml"]
for kind, name, rel in entries:
    out.append(f"{kind}{name} 1.0 {rel}")
(root/"qmldir").write_text("\n".join(out) + "\n")
print(f"qmldir written with {len(entries)} entries")
PY

# --- 3. shader build helper ---------------------------------------------------
cat > shaders/build.sh <<'EOF'
#!/usr/bin/env bash
# Rebuild every .qsb from its .frag. Adjust the flags if you normally use different ones.
cd "$(dirname "$0")"
QSB="${QSB:-$(command -v qsb || echo /usr/lib/qt6/bin/qsb)}"
for f in *.frag; do "$QSB" --qt6 -o "$f.qsb" "$f" && echo "built $f.qsb"; done
EOF
chmod +x shaders/build.sh

# --- 4. things I could not fix automatically ---------------------------------
echo
echo "=== relative file references still worth a look (not shader paths) ==="
grep -rnE '"[^"]*\.(png|jpg|jpeg|svg|json|txt|qml|qsb|ttf|otf|wav|ogg)"' \
     core planets hud widgets map rumor signalscope data 2>/dev/null \
  | grep -vE '\.\./shaders/|hud\.assets|\.qsb' || echo "(none)"
echo
echo "done. test with:  qs -c outerwilds"
echo "if it breaks, restore with: rm -rf $CFG && tar xzf ~/outerwilds-pre-reorg.tar.gz -C $(dirname "$CFG")"
